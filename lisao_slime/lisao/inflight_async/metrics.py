"""In-Flight Async batch metrics for wandb.

Policy lag is computed on the **training batch** (the samples the actor is
about to train), relative to the **actor/policy** last synced
``weight_version``. Critic updates never bump this counter and are not
used for cross-policy / lag. Logged as ``train/inflight/*`` with
``train/step``.

Definitions:

* **policy lag K**: how many actor weight-version steps the current policy
  is ahead of a generated token. One ``weight_version`` bump is one
  **actor** sync to SGLang (critic-only warmup skips this); with
  ``--update-weights-interval 1`` and one optimizer step per rollout that
  equals one actor training step.
  Per sample: K = current - oldest version on that trajectory (GLM-5).
  Per batch: ``policy_lag_max`` is current minus the oldest version in the
  batch; ``policy_lag_mean`` averages sample K; ``policy_lag_mean_token``
  is token-weighted (inflight segments mix versions).
* **cross-policy rollout**: a trajectory whose tokens were generated under
  two or more distinct ``weight_version`` values (abort → resume across a
  weight update).
* **off-policy sample / token**: generated by a policy older than the
  previous version of the current engine (``version < current - 1``).
  The normal 1-step lag (current or current-1, including inflight resume
  across those two) is treated as on-policy.
"""

from __future__ import annotations

import logging
from typing import Any

logger = logging.getLogger("lisao.inflight_async.metrics")

SEGMENT_TOKENS_KEY = "inflight_segment_tokens"

TRAIN_METRIC_PREFIX = "train/inflight"
_METRIC_PREFIX = TRAIN_METRIC_PREFIX


def normalize_weight_version(value: Any) -> str | None:
    if value is None or value == "":
        return None
    text = str(value)
    try:
        return str(int(text))
    except ValueError:
        return text


def record_segment_tokens(sample: Any, prev_response_length: int, prev_num_versions: int) -> None:
    """Append ``{weight_version, num_tokens}`` for the latest generate call."""
    delta = int(getattr(sample, "response_length", 0) or 0) - int(prev_response_length)
    if delta <= 0:
        return
    versions = list(getattr(sample, "weight_versions", None) or [])
    new_versions = versions[int(prev_num_versions) :]
    version = new_versions[-1] if new_versions else (versions[-1] if versions else None)
    meta = getattr(sample, "metadata", None)
    if meta is None:
        sample.metadata = {}
        meta = sample.metadata
    meta.setdefault(SEGMENT_TOKENS_KEY, []).append(
        {
            "weight_version": normalize_weight_version(version),
            "num_tokens": int(delta),
        }
    )


def _sample_versions(sample: Any) -> list[str]:
    out: list[str] = []
    for value in getattr(sample, "weight_versions", None) or []:
        version = normalize_weight_version(value)
        if version is not None:
            out.append(version)
    return out


def _segment_token_counts(sample: Any) -> list[tuple[str | None, int]]:
    meta = getattr(sample, "metadata", None) or {}
    segments = meta.get(SEGMENT_TOKENS_KEY) or []
    if segments:
        return [
            (normalize_weight_version(seg.get("weight_version")), int(seg.get("num_tokens") or 0))
            for seg in segments
        ]
    n_tokens = int(getattr(sample, "response_length", 0) or 0)
    versions = _sample_versions(sample)
    unique = list(dict.fromkeys(versions))
    if len(unique) <= 1:
        return [(unique[0] if unique else None, n_tokens)]
    # Mixed versions but no per-segment lengths: cannot split; leave unattributed.
    return [(None, n_tokens)]


def _version_as_int(value: str | None) -> int | None:
    if value is None:
        return None
    try:
        return int(value)
    except ValueError:
        return None


def policy_lag(version: Any, current_weight_version: Any) -> int | None:
    """``current - version`` in weight-version steps, or ``None`` if unknown.

    Matches GLM-5 / the async-RL survey: lag K is how many policy versions
    the trainer is ahead of the behavior policy that produced the token.
    Negative gaps (version newer than current) clamp to 0.
    """
    version_n = normalize_weight_version(version)
    current_n = normalize_weight_version(current_weight_version)
    if version_n is None or current_n is None:
        return None
    version_i = _version_as_int(version_n)
    current_i = _version_as_int(current_n)
    if version_i is None or current_i is None:
        return None
    return max(0, current_i - version_i)


def sample_oldest_weight_version(sample: Any) -> str | None:
    """Policy version of the first tokens on this trajectory.

    Inflight abort→resume appends ``weight_versions`` in generate order, so
    the first tokens are the oldest version (not the latest resume segment).
    When ``inflight_segment_tokens`` is present, the first non-empty segment
    is the same first-token policy. Numerically oldest wins if they differ.
    """
    versions = list(_sample_versions(sample))
    for version, n_seg in _segment_token_counts(sample):
        if version is not None and n_seg > 0:
            versions.append(version)
            break  # first tokens only; older resume versions come from weight_versions
    return _oldest_version(versions)


def sample_policy_lag(sample: Any, current_weight_version: Any) -> int | None:
    """Per-sample lag K = current − oldest version on the trajectory."""
    return policy_lag(sample_oldest_weight_version(sample), current_weight_version)


def is_stale_weight_version(version: Any, current_weight_version: Any) -> bool:
    """True iff ``version`` is older than the previous policy (``current - 1``).

    PPO/GRPO's one-step lag — data from the current engine version or the
    immediately previous one — is not counted as off-policy.
    """
    lag = policy_lag(version, current_weight_version)
    if lag is None:
        version_n = normalize_weight_version(version)
        current_n = normalize_weight_version(current_weight_version)
        if version_n is None or current_n is None:
            return False
        return version_n != current_n
    return lag > 1


def _oldest_version(versions: list[str]) -> str | None:
    ints = [_version_as_int(v) for v in versions]
    parsed = [i for i in ints if i is not None]
    if not parsed:
        return None
    return str(min(parsed))


def _iter_samples(node: Any) -> list[Any]:
    if node is None:
        return []
    if isinstance(node, list):
        out: list[Any] = []
        for item in node:
            out.extend(_iter_samples(item))
        return out
    return [node]


def samples_from_train_payload(
    weight_versions: list[Any],
    segment_tokens: list[Any] | None = None,
    response_lengths: list[Any] | None = None,
) -> list[Any]:
    """Rebuild sample-like objects from train_data fields for metric computation."""
    from types import SimpleNamespace

    if segment_tokens is None:
        segment_tokens = [[] for _ in weight_versions]
    if response_lengths is None:
        response_lengths = [0 for _ in weight_versions]
    if not (len(weight_versions) == len(segment_tokens) == len(response_lengths)):
        raise ValueError(
            "inflight train payload lengths must match: "
            f"versions={len(weight_versions)} segments={len(segment_tokens)} "
            f"response_lengths={len(response_lengths)}"
        )
    samples: list[Any] = []
    for versions, segs, n_tokens in zip(weight_versions, segment_tokens, response_lengths):
        samples.append(
            SimpleNamespace(
                weight_versions=list(versions or []),
                response_length=int(n_tokens or 0),
                metadata={SEGMENT_TOKENS_KEY: list(segs or [])},
            )
        )
    return samples


def compute_inflight_batch_metrics(
    groups: list[Any],
    current_weight_version: Any = None,
    prefix: str = _METRIC_PREFIX,
) -> dict[str, float | int]:
    """Compute wandb metrics for one training batch."""
    samples = _iter_samples(groups)
    current = normalize_weight_version(current_weight_version)

    n_samples = len(samples)
    n_cross = 0
    n_offpolicy = 0
    n_tokens = 0
    n_offpolicy_tokens = 0
    n_versioned = 0
    sum_n_versions = 0
    sample_lags: list[int] = []
    token_lag_sum = 0
    token_lag_den = 0

    for sample in samples:
        versions = _sample_versions(sample)
        unique = set(versions)
        if unique:
            n_versioned += 1
            sum_n_versions += len(unique)
        if len(unique) >= 2:
            n_cross += 1
        if any(is_stale_weight_version(v, current) for v in unique):
            n_offpolicy += 1

        sample_lag = sample_policy_lag(sample, current)
        if sample_lag is not None:
            sample_lags.append(sample_lag)

        for version, n_seg in _segment_token_counts(sample):
            n_seg = max(0, n_seg)
            n_tokens += n_seg
            if is_stale_weight_version(version, current):
                n_offpolicy_tokens += n_seg
            elif version is None and any(is_stale_weight_version(v, current) for v in unique):
                # Mixed trajectory without per-segment lengths, includes stale versions.
                n_offpolicy_tokens += n_seg

            token_lag = policy_lag(version, current)
            if token_lag is None and version is None:
                token_lag = sample_lag
            if token_lag is not None and n_seg:
                token_lag_sum += token_lag * n_seg
                token_lag_den += n_seg

    def _ratio(num: int, den: int) -> float:
        return float(num) / float(den) if den else 0.0

    return {
        f"{prefix}/num_samples": n_samples,
        f"{prefix}/num_response_tokens": n_tokens,
        f"{prefix}/current_weight_version": int(current) if current is not None and current.isdigit() else -1,
        f"{prefix}/policy_lag_max": max(sample_lags) if sample_lags else 0,
        f"{prefix}/policy_lag_mean": _ratio(sum(sample_lags), len(sample_lags)),
        f"{prefix}/policy_lag_mean_token": _ratio(token_lag_sum, token_lag_den),
        f"{prefix}/cross_policy_count": n_cross,
        f"{prefix}/cross_policy_ratio": _ratio(n_cross, n_samples),
        f"{prefix}/offpolicy_sample_count": n_offpolicy,
        f"{prefix}/offpolicy_sample_ratio": _ratio(n_offpolicy, n_samples),
        f"{prefix}/offpolicy_token_count": n_offpolicy_tokens,
        f"{prefix}/offpolicy_token_ratio": _ratio(n_offpolicy_tokens, n_tokens),
        f"{prefix}/mean_num_weight_versions": _ratio(sum_n_versions, n_versioned) if n_versioned else 0.0,
    }


def log_inflight_train_metrics(
    args: Any,
    rollout_id: int,
    rollout_data: dict[str, Any],
    current_weight_version: Any,
) -> dict[str, float | int] | None:
    """Log policy lag for the batch the actor is about to train, on ``train/step``."""
    versions = rollout_data.get("inflight_weight_versions")
    if not versions or not any(versions):
        return None
    samples = samples_from_train_payload(
        versions,
        rollout_data.get("inflight_segment_tokens"),
        rollout_data.get("inflight_response_lengths"),
    )
    metrics = compute_inflight_batch_metrics(
        samples,
        current_weight_version=current_weight_version,
        prefix=TRAIN_METRIC_PREFIX,
    )
    # Stash onto args so model.train() logs them in the same wandb.log as
    # train/pg_loss with the real accumulated train/step. Nested keys
    # ``train/inflight/*`` do not match wandb's ``train/*`` glob and a
    # separate wandb.log() would sit on default ``_step`` (many more ticks
    # than optimizer steps).
    args._inflight_train_metrics = metrics
    num_steps = len(rollout_data.get("global_batch_sizes") or [1])
    train_step = int(rollout_id) * max(1, num_steps)
    logger.info(
        "inflight-async train rollout %d step=%s: policy_lag max=%s mean=%.3f mean_token=%.3f "
        "cross_policy=%s/%s (%.3f) offpolicy_samples=%s/%s (%.3f) "
        "offpolicy_tokens=%s/%s (%.3f) current_weight_version=%s",
        rollout_id,
        train_step,
        metrics[f"{TRAIN_METRIC_PREFIX}/policy_lag_max"],
        metrics[f"{TRAIN_METRIC_PREFIX}/policy_lag_mean"],
        metrics[f"{TRAIN_METRIC_PREFIX}/policy_lag_mean_token"],
        metrics[f"{TRAIN_METRIC_PREFIX}/cross_policy_count"],
        metrics[f"{TRAIN_METRIC_PREFIX}/num_samples"],
        metrics[f"{TRAIN_METRIC_PREFIX}/cross_policy_ratio"],
        metrics[f"{TRAIN_METRIC_PREFIX}/offpolicy_sample_count"],
        metrics[f"{TRAIN_METRIC_PREFIX}/num_samples"],
        metrics[f"{TRAIN_METRIC_PREFIX}/offpolicy_sample_ratio"],
        metrics[f"{TRAIN_METRIC_PREFIX}/offpolicy_token_count"],
        metrics[f"{TRAIN_METRIC_PREFIX}/num_response_tokens"],
        metrics[f"{TRAIN_METRIC_PREFIX}/offpolicy_token_ratio"],
        metrics[f"{TRAIN_METRIC_PREFIX}/current_weight_version"],
    )
    return metrics
